// Derive dark variants for declared colors; keep imagery and inline user colors intact.
import postcss from 'postcss';
import { readFileSync, writeFileSync } from 'node:fs';
import './generate-platform-theme.mjs';
const source = postcss.parse(readFileSync('src/styles/styles.css', 'utf8'));
const root = postcss.root();
function recolor(value, property) {
  return value.replace(/#[\da-f]{3,8}\b|\bwhite\b|\bblack\b/gi, (raw) => {
    let hex = raw === 'white' ? 'ffffff' : raw === 'black' ? '000000' : raw.slice(1);
    if (hex.length === 3)
      hex = hex
        .split('')
        .map((x) => x + x)
        .join('');
    if (hex.length !== 6 && hex.length !== 8) return raw;
    const r = parseInt(hex.slice(0, 2), 16),
      g = parseInt(hex.slice(2, 4), 16),
      b = parseInt(hex.slice(4, 6), 16);
    const light = (r * 0.2126 + g * 0.7152 + b * 0.0722) / 255;
    const alpha = hex.length === 8 ? hex.slice(6) : '';
    let color;
    if (property === 'color') {
      color = light < 0.35 ? 'e5e5e7' : light < 0.72 ? 'a6a8ae' : 'cacbd0';
    } else if (property.includes('border') || property.includes('outline')) {
      color = light > 0.7 ? '383b42' : light > 0.4 ? '686d78' : hex.slice(0, 6);
    } else if (property.includes('shadow')) color = '000000';
    else {
      color =
        light > 0.96
          ? '232529'
          : light > 0.87
            ? '1b1d21'
            : light > 0.7
              ? '2c2f35'
              : light > 0.5
                ? '444a54'
                : hex.slice(0, 6);
    }
    return '#' + color + alpha;
  });
}
function visit(input, output) {
  for (const node of input.nodes ?? []) {
    if (node.type === 'atrule' && node.name === 'media') {
      const media = postcss.atRule({ name: node.name, params: node.params });
      visit(node, media);
      if (media.nodes?.length) output.append(media);
    } else if (node.type === 'rule') {
      const rule = postcss.rule({
        selector: node.selectors
          .map((s) =>
            s.includes(':root')
              ? s.replace(':root', ':root[data-theme="dark"]')
              : ':root[data-theme="dark"] ' + s,
          )
          .join(','),
      });
      for (const decl of node.nodes ?? []) {
        if (
          decl.type !== 'decl' ||
          !/color|background|border|shadow|outline/.test(decl.prop) ||
          decl.prop.startsWith('--')
        )
          continue;
        const value = recolor(decl.value, decl.prop);
        if (value !== decl.value)
          rule.append({ prop: decl.prop, value, important: decl.important });
      }
      if (rule.nodes?.length) output.append(rule);
    }
  }
}
visit(source, root);
writeFileSync(
  'src/styles/dark.css',
  '/* Generated by scripts/generate-dark-theme.mjs from styles.css. */\n' +
    root.toString() +
    '\n:root[data-theme="dark"]{--line:#383b42;--muted:#a6a8ae;--green:#9aacbf;color-scheme:dark}\n:root[data-theme="dark"] .avatar{color:#26384e}\n:root[data-theme="dark"] .completion-donut>span{background:#232529}\n:root[data-theme="dark"] .has-workspace-banner .banner-text{color:#e5e5e7}\n',
);

writeFileSync(
  'src/styles/dark.css',
  readFileSync('src/styles/dark.css', 'utf8') +
    readFileSync('src/styles/dark-overrides.css', 'utf8'),
);
