// Bridge the existing component styles to shared, administrator-configurable tokens.
import postcss from 'postcss';
import { readFileSync, writeFileSync } from 'node:fs';

const scope = ':is(:root, [data-platform-theme])[data-platform-theme]';
const output = postcss.root();
const semantic =
  /(?:avatar|priority|status-icon|card-label|task-cover|mini-|phone|note\b|orbit|donut|sparkline|destructive|danger|error|warning|success|overdue|notification-item-icon)/;
const fill = /(?:\.primary\b|auth-submit|preview-button)/;
function token(raw, property, selector) {
  let hex =
    raw.toLowerCase() === 'white'
      ? 'ffffff'
      : raw.toLowerCase() === 'black'
        ? '000000'
        : raw.slice(1);
  if (hex.length === 3)
    hex = hex
      .split('')
      .map((c) => c + c)
      .join('');
  if (hex.length !== 6) return raw;
  const rgb = [0, 2, 4].map((start) => parseInt(hex.slice(start, start + 2), 16));
  const light = (rgb[0] * 0.2126 + rgb[1] * 0.7152 + rgb[2] * 0.0722) / 255;
  const tinted = Math.max(...rgb) - Math.min(...rgb) > 24;
  const blue = rgb[2] > rgb[0] && rgb[2] >= rgb[1];
  // Semantic reds, greens, yellows and other content colors are not brand colors.
  if (tinted && !blue) return raw;
  if (property.includes('shadow')) return 'var(--ui-shadow)';
  if (property.includes('outline')) return 'var(--ui-link)';
  if (property.includes('border'))
    return fill.test(selector) ? 'var(--ui-primary)' : 'var(--ui-border)';
  if (property === 'color' || property === 'fill' || property === 'stroke') {
    if (fill.test(selector)) return 'var(--ui-on-primary)';
    return light < 0.4 || light > 0.85 ? 'var(--ui-text)' : 'var(--ui-muted)';
  }
  if (/background/.test(property)) {
    if (fill.test(selector)) return 'var(--ui-primary)';
    if (/sidebar|auth-story/.test(selector) && light < 0.4) return 'var(--ui-sidebar)';
    if (/active|selected|pressed|checked|logo-symbol|progress-track|live-dot/.test(selector))
      return 'var(--ui-accent)';
    if (tinted && blue) return 'var(--ui-selection)';
    if (light > 0.97) return 'var(--ui-surface)';
    if (light > 0.86) return 'var(--ui-field)';
    return 'var(--ui-raised)';
  }
  return raw;
}
function visit(parent, target) {
  for (const node of parent.nodes ?? []) {
    if (node.type === 'atrule' && ['media', 'supports'].includes(node.name)) {
      const rule = postcss.atRule({ name: node.name, params: node.params });
      visit(node, rule);
      if (rule.nodes?.length) target.append(rule);
    }
    if (node.type !== 'rule') continue;
    const selectors = node.selectors.filter(
      (s) => !semantic.test(s) && !s.includes('.platform-preview'),
    );
    if (!selectors.length) continue;
    const rule = postcss.rule({
      selector: selectors
        .map((s) =>
          s.includes(':root') ? s.replace(':root', ':root[data-platform-theme]') : `${scope} ${s}`,
        )
        .join(',\n'),
    });
    for (const declaration of node.nodes ?? []) {
      if (declaration.type !== 'decl' || declaration.prop.startsWith('--')) continue;
      const property = declaration.prop;
      let value = declaration.value;
      if (/color|background|border|shadow|outline|^fill$|^stroke$/.test(property))
        value = value.replace(/#[\da-f]{3,8}\b|\bwhite\b|\bblack\b/gi, (raw) =>
          token(raw, property, selectors.join(',')),
        );
      if (property === 'border-radius' && /^\d+(?:px)(?:\s+\d+px)*$/.test(value))
        value = value.replace(/(\d+)px/g, (raw, number) =>
          Number(number) <= 16 ? `calc(${number}px * var(--ui-radius-scale))` : raw,
        );
      if (property === 'font-size' && /^\d+(?:\.\d+)?px$/.test(value))
        value = `calc(${value} * var(--ui-font-scale))`;
      if (property === 'font-family' || property === 'font')
        value = value
          .replace(/(['"]?)Manrope\1(?:,\s*sans-serif)?/g, 'var(--ui-font-heading)')
          .replace(/(['"]?)DM Sans\1(?:,\s*sans-serif)?/g, 'var(--ui-font-body)');
      if (value !== declaration.value)
        rule.append({ prop: property, value, important: declaration.important });
    }
    if (
      rule.nodes?.some(
        (n) => /background/.test(n.prop) && /--ui-(surface|field|raised)/.test(n.value),
      )
    )
      rule.append({ prop: '--ui-text', value: 'var(--ui-panel-text)' });
    if (rule.nodes?.length) target.append(rule);
  }
}
for (const path of [
  'src/styles/styles.css',
  'src/features/projects/jira-settings.css',
  'src/features/workspaces/platform-settings.css',
])
  visit(postcss.parse(readFileSync(path, 'utf8')), output);
writeFileSync(
  'src/styles/theme-components.css',
  '/* Generated by scripts/generate-platform-theme.mjs. Do not edit. */\n' +
    output.toString() +
    '\n',
);
